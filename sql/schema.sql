create table if not exists public.contactos (
    id_contacto bigint generated by default as identity primary key,
    nombre text not null,
    email text not null,
    telefono text not null,
    foto text not null default 'default.png'
);

create table if not exists public.sesiones_abiertas (
    token text primary key
);

alter table public.contactos enable row level security;
alter table public.sesiones_abiertas enable row level security;

drop policy if exists "contactos_anon_crud" on public.contactos;
create policy "contactos_anon_crud" on public.contactos
    for all to anon
    using (true)
    with check (true);

drop policy if exists "contactos_auth_crud" on public.contactos;
create policy "contactos_auth_crud" on public.contactos
    for all to authenticated
    using (true)
    with check (true);

drop policy if exists "sesiones_anon_crud" on public.sesiones_abiertas;
create policy "sesiones_anon_crud" on public.sesiones_abiertas
    for all to anon
    using (true)
    with check (true);

drop policy if exists "sesiones_auth_crud" on public.sesiones_abiertas;
create policy "sesiones_auth_crud" on public.sesiones_abiertas
    for all to authenticated
    using (true)
    with check (true);
